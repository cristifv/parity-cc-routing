int main(int argc, char** argv) {
  uint64_t from = 1, to = 20;
  std::string save, contracts, dump;
  bool expect_find = false;
  int determinism = 0, max_runs = 250;
  g_opt.deterministic = true;
  for (int i = 1; i < argc; ++i) {
    const std::string a = argv[i];
    if (a.rfind("--seeds=", 0) == 0) {
      const std::string r = a.substr(8);
      from = std::stoull(r.substr(0, r.find(':')));
      to = std::stoull(r.substr(r.find(':') + 1));
    } else if (a.rfind("--save=", 0) == 0) {
      save = a.substr(7);
    } else if (a.rfind("--fault=", 0) == 0) {
      const std::string f = a.substr(8);
      g_opt.fault.kind = f.substr(0, f.find('@'));
      g_opt.fault.at_ms = static_cast<int64_t>(std::stod(f.substr(f.find('@') + 1)) * 1000);
    } else if (a == "--expect-find") {
      expect_find = true;
    } else if (a.rfind("--determinism=", 0) == 0) {
      determinism = std::stoi(a.substr(14));
    } else if (a.rfind("--max-shrink-runs=", 0) == 0) {
      max_runs = std::stoi(a.substr(18));
    } else if (a.rfind("--contracts=", 0) == 0) {
      contracts = a.substr(12);
    } else if (a.rfind("--dump-only=", 0) == 0) {
      dump = a.substr(12);
    }
  }
  if (!dump.empty()) {
    // The generator's output for the schema check (tests/scenarios/validate.py in scripts/ci.sh).
    for (uint64_t seed = from; seed <= to; ++seed) {
      std::ofstream(dump + "/search-" + std::to_string(seed) + ".json") << generate(seed).dump(2) << "\n";
    }
    std::printf("dumped %llu scenarios\n", static_cast<unsigned long long>(to - from + 1));
    return 0;
  }
  if (save.empty()) {
    if (const char* out = std::getenv("TEST_UNDECLARED_OUTPUTS_DIR")) save = out;
  }
  int found = 0, bad = 0, ran = 0;
  // CR-049: the same scenario twice gives the same run (counts, outcomes, violations).
  for (uint64_t seed = from; seed < from + static_cast<uint64_t>(determinism) && seed <= to; ++seed) {
    json a, b;
    const json sc = generate(seed);
    violated(sc, &a);
    violated(sc, &b);
    const bool same = a["engine"] == b["engine"] && a["occurred"] == b["occurred"] && a["tenants"] == b["tenants"] &&
                      a["violation_count"] == b["violation_count"];
    std::printf("determinism seed %llu: %s\n", static_cast<unsigned long long>(seed), same ? "same" : "DIFFERENT");
    if (!same) {
      std::printf("  first:  %s\n  second: %s\n", a["engine"].dump().c_str(), b["engine"].dump().c_str());
      ++bad;
    }
  }
  for (uint64_t seed = from; seed <= to; ++seed) {
    const json sc = generate(seed);
    json report;
    const auto v = violated(sc, &report);
    ++ran;
    if (v.empty()) {
      std::printf("PASS search-%llu (%d tenants, size %d)\n", static_cast<unsigned long long>(seed),
                  static_cast<int>(sc["tenants"].size()), size_of(sc));
      std::fflush(stdout);
      continue;
    }
    ++found;
    std::string vs;
    for (const auto& x : v) vs += " " + x;
    std::printf("FAIL search-%llu:%s: %s\n", static_cast<unsigned long long>(seed), vs.c_str(),
                report.value("violations", json::array()).dump().substr(0, 400).c_str());
    int runs = 0;
    json small = shrink(sc, v, max_runs, &runs);
    // A regression must fail on its own, twice (deterministic), with the same invariant.
    const auto v1 = violated(small), v2 = violated(small);
    std::string inv = *v.begin();
    for (const auto& t : v) {
      if (v1.contains(t)) {
        inv = t;
        break;
      }
    }
    const bool repro = v1.contains(inv) && v2.contains(inv);
    std::string lc = inv;
    std::transform(lc.begin(), lc.end(), lc.begin(), [](unsigned char c) { return std::tolower(c); });
    small["name"] = "regression-" + lc + "-seed-" + std::to_string(seed);
    small["description"] = "Found by the invariant search (seed " + std::to_string(seed) + ", " + inv + "), shrunk from size " +
                           std::to_string(size_of(sc)) + " to " + std::to_string(size_of(small)) + " in " +
                           std::to_string(runs) + " runs: " +
                           first_violation(report).substr(0, 300);
    std::printf("  shrunk to size %d in %d runs; reproduces twice: %s\n%s\n", size_of(small), runs, repro ? "yes" : "NO",
                small.dump(2).c_str());
    if (!repro) ++bad;
    if (!save.empty()) {
      std::ofstream(save + "/" + small["name"].get<std::string>() + ".json") << small.dump(2) << "\n";
      if (!g_opt.fault.kind.empty()) {
        // With a planted fault the shrunk scenario must pass once the fault is gone.
        auto opt = g_opt;
        g_opt.fault = {};
        const auto clean = violated(small);
        g_opt = opt;
        std::printf("  without the fault: %s\n", clean.empty() ? "passes" : "STILL FAILS");
        if (!clean.empty()) ++bad;
      }
    }
    std::fflush(stdout);
  }
  std::printf("search: %d scenarios, %d failing, %d problems\n", ran, found, bad);
  if (expect_find) return found > 0 && bad == 0 ? 0 : 1;
  return found == 0 && bad == 0 ? 0 : 1;
}
