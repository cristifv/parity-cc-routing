struct Gen {
  std::mt19937_64 r;
  explicit Gen(uint64_t seed) : r(seed * 0x9E3779B97F4A7C15ULL + 7) {}
  double u(double a, double b) { return std::uniform_real_distribution<double>(a, b)(r); }
  int i(int a, int b) { return std::uniform_int_distribution<int>(a, b)(r); }
  bool p(double x) { return u(0, 1) < x; }
  double round1(double x) { return std::round(x * 10) / 10; }

  json dist(double lo, double hi) {
    const double mean = round1(u(lo, hi));
    switch (i(0, 2)) {
      case 0: return {{"kind", "exponential"}, {"mean_s", mean}};
      case 1: return {{"kind", "lognormal"}, {"mean_s", mean}, {"cv", round1(u(0.3, 1.5))}};
      default: return {{"kind", "fixed"}, {"s", mean}};
    }
  }
  json spikes(double duration) {
    json s = json::array();
    for (int k = 0, n = i(0, 2); k < n; ++k) {
      s.push_back({{"start_s", round1(u(0, duration * 0.8))}, {"duration_s", round1(u(20, 300))},
                   {"multiplier", round1(u(2, 20))}, {"ramp_s", round1(p(0.5) ? 0 : u(0, 60))}});
    }
    return s;
  }
  json arrivals(double duration) {
    json a;
    switch (i(0, 3)) {
      case 0: {
        json v = json::array();
        for (int k = 0, n = i(1, 6); k < n; ++k) v.push_back(round1(u(0, 150)));
        a = {{"kind", "piecewise"}, {"bucket_s", 300}, {"per_hour", v}};
        break;
      }
      case 1: {
        json v = json::array();
        for (int k = 0, n = i(1, 6); k < n; ++k) v.push_back(round1(u(0.1, 1)));
        a = {{"kind", "profile"}, {"bucket_s", 300}, {"shape", v}, {"scale_per_hour", round1(u(5, 200))}};
        break;
      }
      case 2: {
        json pts = json::array();
        double t = 0;
        for (int k = 0, n = i(1, 4); k < n; ++k) {
          pts.push_back({{"t_s", round1(t)}, {"per_hour", round1(u(0, 150))}});
          t += u(60, duration / 2);
        }
        a = {{"kind", "poisson"}, {"points", pts}};
        break;
      }
      default: {
        json v = json::array();
        for (int k = 0, n = i(0, 25); k < n; ++k) v.push_back(round1(u(0, duration)));
        std::vector<double> s = v.get<std::vector<double>>();
        std::sort(s.begin(), s.end());
        return {{"kind", "list"}, {"at_s", s}};
      }
    }
    if (p(0.4)) a["spikes"] = spikes(duration);
    return a;
  }
};

const std::vector<std::string> kTenants = {"acme", "globex", "initech-de", "initech-uk"};
const std::vector<std::string> kQueues = {"sales", "support", "billing"};

json generate(uint64_t seed) {
  Gen g(seed);
  const int duration = g.i(300, 1800);
  json sc = {{"schema_version", 1}, {"name", "search-" + std::to_string(seed)},
             {"description", "Generated by the invariant search (parity-cc-routing PLAN §7.1)"},
             {"seed", seed}, {"duration_s", duration}, {"bin", "bin-a"}};
  std::vector<std::string> tenants = kTenants;
  std::shuffle(tenants.begin(), tenants.end(), g.r);
  tenants.resize(g.i(1, 3));
  json tj = json::array(), events = json::array();
  for (const auto& tid : tenants) {
    json t = {{"id", tid}, {"queues", json::array()}, {"agents", json::array()}};
    const int nq = g.i(1, 3);
    for (int q = 0; q < nq; ++q) {
      json qj = {{"id", kQueues[q]}, {"max_wait_s", g.i(20, 600)}, {"arrivals", g.arrivals(duration)},
                 {"handle_time", g.dist(10, 300)}, {"patience", g.dist(5, 600)}};
      const int act = g.i(0, 2);
      if (act == 0 || q + 1 == nq) {
        qj["max_wait_action"] = {{"action", g.p(0.5) ? "disconnect" : "flow_step"}};
        if (qj["max_wait_action"]["action"] == "flow_step") qj["max_wait_action"]["flow_step"] = "voicemail-menu";
      } else {
        qj["max_wait_action"] = {{"action", "queue"}, {"queue_id", kQueues[g.i(q + 1, nq - 1)]}};  // acyclic
      }
      if (g.p(0.2)) qj["max_entries"] = g.i(2, 30);
      if (g.p(0.5)) qj["offer_timeout_s"] = g.i(5, 30);
      if (g.p(0.5)) qj["wrap_up_limit_s"] = g.i(0, 120);
      if (g.p(0.5)) qj["sla_s"] = g.i(5, 60);
      if (g.p(0.3)) qj["escalate_after_s"] = g.i(5, 180);
      if (g.p(0.2)) qj["required_skills"] = json::array({{{"skill_id", "de"}, {"min_level", g.i(1, 3)}}});
      if (g.p(0.2)) qj["priority_mix"] = json::array({{{"priority", 90}, {"share", g.round1(g.u(0.1, 0.5))}}});
      t["queues"].push_back(qj);
    }
    const int ng = g.i(0, 3);
    for (int k = 0; k < ng; ++k) {
      json grp = {{"count", g.i(1, 8)}, {"id_prefix", tid + "-g" + std::to_string(k)}, {"queues", json::array()}};
      for (int q = 0; q < nq; ++q) {
        if (g.p(0.6) || (q == nq - 1 && grp["queues"].empty())) grp["queues"].push_back(kQueues[q]);
      }
      if (g.p(0.5)) grp["skills"] = {{"de", g.i(1, 5)}};
      grp["site"] = g.p(0.5) ? "site-a" : "site-b";
      if (g.p(0.3)) {
        const double in = g.round1(g.u(0, duration / 3.0));
        grp["shifts"] = json::array({{{"login_s", in}, {"logout_s", g.round1(g.u(in + 30, duration * 1.2))}}});
      }
      t["agents"].push_back(grp);
    }
    if (g.p(0.7)) {
      json b = json::object();
      if (g.p(0.5)) b["p_reject"] = g.round1(g.u(0, 0.3));
      if (g.p(0.4)) b["p_ignore"] = g.round1(g.u(0, 0.2));
      if (g.p(0.3)) b["p_leg_failed"] = g.round1(g.u(0, 0.1));
      if (g.p(0.3)) b["p_no_answer"] = g.round1(g.u(0, 0.1));
      if (g.p(0.5)) b["answer_delay"] = g.dist(0.5, 8);
      if (g.p(0.6)) b["wrap_up"] = g.dist(1, 60);
      t["behaviour"] = b;
    }
    if (g.p(0.3)) t["reject_skip_s"] = g.i(0, 60);
    if (g.p(0.3)) t["owner_loss_s"] = g.i(10, 120);
    tj.push_back(t);
    // Events for this tenant.
    for (int k = 0, n = g.i(0, 2); k < n; ++k) {
      const double at = g.round1(g.u(0, duration * 0.9));
      switch (g.i(0, 2)) {
        case 0: {
          json e = {{"at_s", at}, {"kind", "agent_outage"}, {"tenant", tid}, {"percent", g.i(10, 100)}};
          if (!t["agents"].empty() && g.p(0.5)) e["site"] = t["agents"][0]["site"];
          if (g.p(0.7)) e["down_s"] = g.round1(g.u(5, 300));
          events.push_back(e);
          break;
        }
        case 1:
          events.push_back({{"at_s", at}, {"kind", "mass_logout"}, {"tenant", tid}, {"percent", g.i(10, 100)}});
          break;
        default: {
          json grp = {{"count", g.i(1, 10)}, {"id_prefix", tid + "-late" + std::to_string(k)},
                      {"queues", json::array({t["queues"][g.i(0, nq - 1)]["id"]})}};
          events.push_back({{"at_s", at}, {"kind", "mass_login"}, {"tenant", tid}, {"group", grp}, {"over_s", g.round1(g.u(0, 120))}});
        }
      }
    }
  }
  // Stack-wide events: stream losses, restarts.
  for (int k = 0, n = g.i(0, 2); k < n; ++k) {
    const double at = g.round1(g.u(0, duration * 0.9));
    switch (g.i(0, 3)) {
      case 0: events.push_back({{"at_s", at}, {"kind", "ie_stream_lost"}, {"down_s", g.round1(g.u(1, 40))}}); break;
      case 1: events.push_back({{"at_s", at}, {"kind", "gateway_disconnect"}, {"down_s", g.round1(g.u(1, 40))}}); break;
      case 2: events.push_back({{"at_s", at}, {"kind", "re_restart"}}); break;
      default: events.push_back({{"at_s", at}, {"kind", "ie_restart"}, {"down_s", g.round1(g.u(1, 30))}}); break;
    }
  }
  sc["tenants"] = tj;
  if (!events.empty()) sc["events"] = events;
  sc["expectations"] = {{"invariants", "all"}, {"rss_mib_max", 1024}};
  return sc;
}

// ---- running and judging ----

pcr::scenario::RunOptions g_opt;

std::set<std::string> violated(const json& sc, json* report = nullptr) {
  json r;
  try {
    r = pcr::scenario::run(sc, g_opt);
  } catch (const std::exception& e) {
    r = {{"violated", {{"crash", 1}}}, {"violations", {e.what()}}, {"violation_count", 1}};
  }
  std::set<std::string> v;
  for (const auto& [k, n] : r.value("violated", json::object()).items()) {
    if (n.get<uint64_t>() > 0 && k != "fault") v.insert(k);  // "the fault found nothing to break" isn't a finding
  }
  if (report) *report = r;
  return v;
}

std::string first_violation(const json& report) {
  const json v = report.value("violations", json::array());
  return v.empty() || !v[0].is_string() ? std::string() : v[0].get<std::string>();
}

// ---- shrinking ----

int size_of(const json& sc) {
  int n = sc.value("events", json::array()).size() * 3 + sc.at("duration_s").get<int>() / 100;
  for (const auto& t : sc.at("tenants")) {
    n += 5 + t.at("queues").size() * 3;
    for (const auto& g : t.at("agents")) n += g.at("count").get<int>();
  }
  return n;
}

// Drops a queue and everything naming it.
void drop_queue(json& t, size_t qi) {
  const std::string id = t["queues"][qi]["id"];
  t["queues"].erase(qi);
  for (auto& q : t["queues"]) {
    if (q["max_wait_action"].value("queue_id", "") == id) q["max_wait_action"] = {{"action", "disconnect"}};
  }
  json groups = json::array();
  for (auto g : t["agents"]) {
    json qs = json::array();
    for (const auto& q : g["queues"]) {
      if (q != id) qs.push_back(q);
    }
    if (qs.empty()) continue;
    g["queues"] = qs;
    groups.push_back(g);
  }
  t["agents"] = groups;
}

void fix_events(json& sc) {
  if (!sc.contains("events")) return;
  std::set<std::string> tenants;
  std::map<std::string, std::set<std::string>> queues, sites;
  for (const auto& t : sc["tenants"]) {
    tenants.insert(t["id"]);
    for (const auto& q : t["queues"]) queues[t["id"]].insert(q["id"]);
    for (const auto& g : t["agents"]) {
      if (g.contains("site")) sites[t["id"]].insert(g["site"]);
    }
  }
  json keep = json::array();
  const double dur = sc["duration_s"];
  for (auto e : sc["events"]) {
    if (e["at_s"].get<double>() > dur) continue;
    if (e.contains("tenant") && !tenants.contains(e["tenant"])) continue;
    if (e.contains("site") && !sites[e.value("tenant", "")].contains(e["site"])) e.erase("site");
    if (e["kind"] == "mass_login") {
      json qs = json::array();
      for (const auto& q : e["group"]["queues"]) {
        if (queues[e["tenant"]].contains(q)) qs.push_back(q);
      }
      if (qs.empty()) continue;
      e["group"]["queues"] = qs;
    }
    keep.push_back(e);
  }
  if (keep.empty()) sc.erase("events");
  else sc["events"] = keep;
}

std::vector<json> candidates(const json& sc) {
  std::vector<json> out;
  auto push = [&](json c) {
    fix_events(c);
    if (!c["tenants"].empty()) out.push_back(std::move(c));
  };
  const size_t ne = sc.value("events", json::array()).size();
  for (size_t k = 0; k < ne; ++k) {
    json c = sc;
    c["events"].erase(k);
    push(c);
  }
  for (size_t t = 0; t < sc["tenants"].size() && sc["tenants"].size() > 1; ++t) {
    json c = sc;
    c["tenants"].erase(t);
    push(c);
  }
  if (sc["duration_s"].get<int>() > 60) {
    json c = sc;
    c["duration_s"] = std::max(60, sc["duration_s"].get<int>() / 2);
    push(c);
  }
  for (size_t t = 0; t < sc["tenants"].size(); ++t) {
    const json& tj = sc["tenants"][t];
    for (size_t q = 0; q < tj["queues"].size() && tj["queues"].size() > 1; ++q) {
      json c = sc;
      drop_queue(c["tenants"][t], q);
      push(c);
    }
    for (size_t g = 0; g < tj["agents"].size(); ++g) {
      json c = sc;
      c["tenants"][t]["agents"].erase(g);
      push(c);
      const int n = tj["agents"][g]["count"];
      if (n > 1) {
        json d = sc;
        d["tenants"][t]["agents"][g]["count"] = n / 2;
        push(d);
      }
      for (const char* k : {"shifts", "skills"}) {
        if (tj["agents"][g].contains(k)) {
          json e = sc;
          e["tenants"][t]["agents"][g].erase(k);
          push(e);
        }
      }
    }
    if (tj.contains("behaviour") && !tj["behaviour"].empty()) {
      for (const auto& [k, v] : tj["behaviour"].items()) {
        json c = sc;
        c["tenants"][t]["behaviour"].erase(k);
        push(c);
      }
    }
    for (const char* k : {"reject_skip_s", "owner_loss_s"}) {
      if (tj.contains(k)) {
        json c = sc;
        c["tenants"][t].erase(k);
        push(c);
      }
    }
    for (size_t q = 0; q < tj["queues"].size(); ++q) {
      const json& qj = tj["queues"][q];
      if (qj["arrivals"].contains("spikes")) {
        json c = sc;
        c["tenants"][t]["queues"][q]["arrivals"].erase("spikes");
        push(c);
      }
      if (qj["arrivals"]["kind"] != "list") {
        // A constant rate at the function's first value.
        json c = sc;
        const json& a = qj["arrivals"];
        double ph = a["kind"] == "piecewise" ? a["per_hour"][0].get<double>()
                    : a["kind"] == "profile" ? a["scale_per_hour"].get<double>()
                                             : a["points"][0]["per_hour"].get<double>();
        c["tenants"][t]["queues"][q]["arrivals"] = {{"kind", "poisson"}, {"points", json::array({{{"t_s", 0}, {"per_hour", ph}}})}};
        if (a != c["tenants"][t]["queues"][q]["arrivals"]) push(c);
        json h = sc;
        auto& pts = h["tenants"][t]["queues"][q]["arrivals"];
        if (a["kind"] == "poisson" && a["points"].size() == 1 && ph > 1) {
          pts["points"][0]["per_hour"] = std::round(ph / 2);
          push(h);
        }
      } else if (!qj["arrivals"]["at_s"].empty()) {
        json c = sc;
        auto& v = c["tenants"][t]["queues"][q]["arrivals"]["at_s"];
        v.erase(v.size() - 1);
        push(c);
      }
      for (const char* d : {"handle_time", "patience"}) {
        if (qj[d]["kind"] != "fixed") {
          json c = sc;
          c["tenants"][t]["queues"][q][d] = {{"kind", "fixed"}, {"s", qj[d]["mean_s"]}};
          push(c);
        }
      }
      for (const char* k : {"max_entries", "offer_timeout_s", "wrap_up_limit_s", "sla_s", "escalate_after_s",
                            "required_skills", "priority_mix"}) {
        if (qj.contains(k)) {
          json c = sc;
          c["tenants"][t]["queues"][q].erase(k);
          push(c);
        }
      }
    }
  }
  return out;
}

json shrink(json sc, const std::set<std::string>& target, int max_runs, int* runs) {
  auto fails = [&](const json& c) {
    ++*runs;
    const auto v = violated(c);
    for (const auto& t : target) {
      if (v.contains(t)) return true;
    }
    return false;
  };
  bool progress = true;
  while (progress && *runs < max_runs) {
    progress = false;
    for (json& c : candidates(sc)) {
      if (*runs >= max_runs) break;
      if (size_of(c) >= size_of(sc)) continue;
      if (fails(c)) {
        sc = std::move(c);
        progress = true;
        break;
      }
    }
  }
  return sc;
}

