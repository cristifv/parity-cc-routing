// The invariant search (PLAN §7.1, phase 2): a seeded generator of valid routing-scenario.v1
// documents (several tenants, queues with every max-wait action, arrival functions with spikes,
// distributions, agent behaviour, outages, logins and logouts, stream losses, restarts), each played
// against the real engine by the scenario runner (deterministic: CR-049). A failing scenario is
// shrunk greedily (fewer events, tenants, queues, agents, a shorter day, simpler arrivals and
// distributions) while it keeps failing the same invariant, and the minimal JSON is saved as a
// regression file (tests/scenarios/regressions/) that CI replays.
//   search --contracts=<VERSION> --seeds=A:B [--save=<dir>] [--fault=kind@s --expect-find]
//          [--determinism=N] [--max-shrink-runs=N]
